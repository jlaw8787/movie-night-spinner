/* Builds the page's film data from the source files. Run after changing any of them:
     node scripts/build-data.cjs
   Sources (never loaded by the page):
     data/films.json        every film, with full dish methods and shopping
     movie-menus.js         the 124 finished poster menus
     data/recipes/*.json    exact 4-person recipes for every other film
   Output:
     films.js               the light index the page starts with: titles, years and themes only
     data/film/<slug>.json  one file per film, fetched when the film is opened
     data/dish-names.json   every film's dish names, for the seasonal shelves and the Candy bar, fetched once the page settles
     data/dish-notes.json   dish notes for the Candy bar search, fetched when the Candy bar opens */
const fs = require('fs'), path = require('path'), vm = require('vm'), crypto = require('crypto');
const root = path.join(__dirname, '..');
const rd = p => fs.readFileSync(path.join(root, p), 'utf8');
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const films = JSON.parse(rd('data/films.json'));
const ctx = {}; vm.createContext(ctx);
vm.runInContext(rd('movie-menus.js') + ';this.E=MOVIE_MENU_EDITIONS', ctx);
const EDITIONS = ctx.E;

const C = ['S', 'M', 'W', 'K'];
const lite = [], names = {}, notes = {};
fs.mkdirSync(path.join(root, 'data/film'), { recursive: true });
const keep = new Set();
let missing = 0;
for (const f of films) {
  const id = f.title + ' (' + f.year + ')', s = slug(id);
  const o = { title: f.title, year: f.year, theme: f.theme };
  if (f.hw) o.hw = f.hw;
  if (EDITIONS[id]) o.e = 1;
  lite.push(o);
  names[id] = C.map(k => (f[k] || []).map(d => d[0]));
  notes[id] = C.map(k => (f[k] || []).map(d => d[1] || ''));
  const out = { T: f.T, D: f.D, P: f.P };
  for (const k of C) out[k] = f[k] || [];
  if (EDITIONS[id]) out.edition = EDITIONS[id];
  else {
    const rp = path.join(root, 'data/recipes', s + '.json');
    if (fs.existsSync(rp)) out.recipe = JSON.parse(fs.readFileSync(rp, 'utf8'));
    else missing++;
  }
  fs.writeFileSync(path.join(root, 'data/film', s + '.json'), JSON.stringify(out));
  keep.add(s + '.json');
}
for (const n of fs.readdirSync(path.join(root, 'data/film'))) if (!keep.has(n)) fs.unlinkSync(path.join(root, 'data/film', n));
fs.writeFileSync(path.join(root, 'films.js'),
  '/* Generated by scripts/build-data.cjs from data/films.json. Do not edit by hand. */\nconst FILMS=' + JSON.stringify(lite) +
  '.map(e=>Object.assign(e,{id:e.title+" ("+e.year+")"}));\n');
fs.writeFileSync(path.join(root, 'data/dish-names.json'), JSON.stringify(names));
fs.writeFileSync(path.join(root, 'data/dish-notes.json'), JSON.stringify(notes));

/* stamp every local script with a content hash so phones pick up changes straight away */
const hash = p => crypto.createHash('sha1').update(fs.readFileSync(path.join(root, p))).digest('hex').slice(0, 8);
let html = rd('index.html');
html = html.replace(/(src|href)="([\w.-]+\.(?:js|css))(\?v=[\w_]+)?"/g, (m, a, f) => fs.existsSync(path.join(root, f)) ? `${a}="${f}?v=${hash(f)}"` : m);
fs.writeFileSync(path.join(root, 'index.html'), html);
let sw = rd('sw.js');
const ver = crypto.createHash('sha1').update(html + rd('app.js') + rd('formats.js') + rd('films.js')).digest('hex').slice(0, 8);
sw = sw.replace(/const VERSION = '[^']*'/, `const VERSION = 'mns-${ver}'`);
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`films ${lite.length}, editions ${lite.filter(f => f.e).length}, missing recipes ${missing}`);
