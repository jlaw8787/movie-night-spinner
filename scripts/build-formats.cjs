/* Splits formats.js (the source you edit) into what the page actually loads:
     formats-core.js      shared helpers, the phone view and a small index of which film uses which menu
     formats/<fmt>.js     one file per menu: its renderer, the film spec, phone colours and fonts
   The page loads formats-core.js up front and fetches a menu file only when that film is opened,
   so adding more menus no longer makes the first load heavier.
   Run by scripts/build-data.cjs. Never edit the generated files by hand. */
const fs = require('fs'), path = require('path'), vm = require('vm'), crypto = require('crypto');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'formats.js'), 'utf8');

const ctx = { ESC: x => x };
vm.createContext(ctx);
vm.runInContext(src + ';this.F=FMT_FILMS;this.P=FMT_PHONE;this.FO=FMT_FONTS;this.FA=FMT_FAMS;', ctx);
const F = ctx.F, P = ctx.P, FO = ctx.FO, FA = ctx.FA;

const r0 = src.indexOf('const FMT_RENDER=');
if (r0 < 0) throw new Error('FMT_RENDER not found in formats.js');
const renderLit = src.slice(r0, src.indexOf('};', r0) + 2);
const pairs = [...renderLit.matchAll(/(\w+):(?:\(\.\.\.a\)=>)?(fmt\w+)/g)].map(m => [m[1], m[2]]);

/* top-level declarations and where each one ends */
const decls = [];
const re = /^(?:function\s+(\w+)|const\s+(\w+)\s*=|let\s+(\w+)\s*=)/gm;
let m;
while ((m = re.exec(src))) decls.push({ at: m.index, name: m[1] || m[2] || m[3] });
decls.forEach((d, i) => { d.end = i + 1 < decls.length ? decls[i + 1].at : src.length; });
const byName = Object.fromEntries(decls.map(d => [d.name, d]));

const DATA = new Set(['FMT_FILMS', 'FMT_PHONE', 'FMT_FONTS', 'FMT_FAMS', 'FMT_RENDER']);
const rendererNames = new Set(pairs.map(p => p[1]));
for (const n of rendererNames) if (!byName[n]) throw new Error('renderer not found: ' + n);

/* core: everything that is not a renderer or per-menu data */
let core = src.slice(0, decls[0].at);
for (const d of decls) {
  if (rendererNames.has(d.name)) continue;
  if (DATA.has(d.name)) { core += { FMT_FILMS: 'const FMT_FILMS={};\n', FMT_PHONE: 'const FMT_PHONE={};\n', FMT_FONTS: 'const FMT_FONTS={};\n', FMT_FAMS: 'const FMT_FAMS={};\n', FMT_RENDER: 'const FMT_RENDER={};\n' }[d.name]; continue; }
  core += src.slice(d.at, d.end);
}
for (const n of rendererNames) if (new RegExp('\\b' + n + '\\b').test(core)) throw new Error(n + ' is used outside its menu, keep it shared');

const outDir = path.join(root, 'formats');
fs.mkdirSync(outDir, { recursive: true });
const keep = new Set(), versions = {}, index = {};
const hash = s => crypto.createHash('sha1').update(s).digest('hex').slice(0, 8);
for (const [fmt, fn] of pairs) {
  const films = Object.fromEntries(Object.entries(F).filter(([, v]) => v.fmt === fmt));
  for (const id of Object.keys(films)) index[id] = fmt;
  const d = byName[fn];
  const body = `/* Generated by scripts/build-formats.cjs from formats.js. Do not edit by hand. */\n` +
    src.slice(d.at, d.end).trimEnd() + '\n' +
    `FMT_RENDER[${JSON.stringify(fmt)}]=${fn};\n` +
    `Object.assign(FMT_FILMS,${JSON.stringify(films)});\n` +
    `FMT_PHONE[${JSON.stringify(fmt)}]=${JSON.stringify(P[fmt])};\n` +
    `FMT_FONTS[${JSON.stringify(fmt)}]=${JSON.stringify(FO[fmt])};\n` +
    `FMT_FAMS[${JSON.stringify(fmt)}]=${JSON.stringify(FA[fmt])};\n`;
  fs.writeFileSync(path.join(outDir, fmt + '.js'), body);
  keep.add(fmt + '.js');
  versions[fmt] = hash(body);
}
for (const n of fs.readdirSync(outDir)) if (!keep.has(n)) fs.unlinkSync(path.join(outDir, n));

const loader = `
/* which film uses which printed menu, and the version of each menu file (generated) */
const FMT_INDEX=${JSON.stringify(index)};
const FMT_VER=${JSON.stringify(versions)};
const _fmtLoads={};
/* fetch a film's menu file the first time it is needed; resolves straight away when there is none */
function fmtLoad(f){
  const k=f&&FMT_INDEX[f.id];
  if(!k||FMT_RENDER[k]||typeof document==="undefined")return Promise.resolve();
  return _fmtLoads[k]||(_fmtLoads[k]=new Promise(ok=>{
    const s=document.createElement("script");s.src="formats/"+k+".js?v="+FMT_VER[k];
    s.onload=ok;s.onerror=()=>{delete _fmtLoads[k];ok()};document.head.appendChild(s);
  }));
}
`;
const header = '/* Generated by scripts/build-formats.cjs from formats.js. Do not edit by hand: edit formats.js and run node scripts/build-data.cjs */\n';
fs.writeFileSync(path.join(root, 'formats-core.js'), header + core.trimEnd() + '\n' + loader);
console.log(`formats: core ${(Buffer.byteLength(core) / 1024).toFixed(0)}KB, ${pairs.length} menu files`);
