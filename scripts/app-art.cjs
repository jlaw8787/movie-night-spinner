#!/usr/bin/env node
/* Builds app-art.js, the list of pictures the app build leaves out (docs/ARTWORK-RIGHTS.md, option E).
   The website never loads it. app-mode.js loads it when the page runs as the app.

   - swap: Galaxy Video photos that show film posters (the shopfront, the aisles, the late show curtain), and the app copies made by scripts/app-hero.py.
   - block: menu pictures under assets/era that are film stills, or photos docs/image-credits.md gives
     no clear free licence for. Paper, wear and grain textures, drawn props and credited public domain
     or free licence photos stay. Anything not credited and not a plain texture or prop is blocked,
     so the list errs on the safe side. Check it before launch and move any cleared picture out.
   - prefix: whole folders that never go in the app: the 124 generated posters and the film frame.
   - posters: original poster art per film, if any exists. Put a picture at assets/type-posters/<film-file-name>.webp
     (or .jpg or .png; the name matches data/film/<name>.json) and run this again. The app shows it in place of the
     type poster it draws itself.

   Run from the repo root: node scripts/app-art.cjs (npm run build:app runs it too). */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const rel = p => path.relative(ROOT, p).split(path.sep).join('/');
const walk = d => fs.existsSync(d) ? fs.readdirSync(d, {withFileTypes: true}).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]) : [];

/* what docs/image-credits.md says about each picture name */
const credits = new Map();
for (const line of fs.readFileSync(path.join(ROOT, 'docs/image-credits.md'), 'utf8').split('\n')) {
  if (!line.startsWith('- ')) continue;
  const head = line.slice(0, Math.max(line.indexOf(':'), 0) || 200);
  const film = /TMDB|film still|still from/i.test(line);
  for (const m of head.matchAll(/([a-z0-9][a-z0-9_-]*)\.(?:jpg|jpeg|png|webp|svg)/gi)) {
    const k = m[1].toLowerCase(), o = credits.get(k) || {film: false, free: false};
    if (film) o.film = true; else o.free = true;
    credits.set(k, o);
  }
}
/* plain textures and drawn props that carry nothing from a film */
const PROP = /^(?:.*wear.*|paper.*|grain.*|gloss.*|sheen.*|light-(?:front|back)|kraft.*|slate.*|.*stain.*|coffee-ring|paperclip|tack|tape.*|pencil.*|gingham.*|engrav.*|spiral.*|coaster.*|guest-check|bag-paper.*|train-ink|route-pen|check-strip|border-.*|mark-b|cup|mug|milk|almonds|cake|cookie|berry-\d+|jugs|samovar|spot-.*|cannoli-box|mulberry|baseball)$/;
const stem = f => path.basename(f).replace(/-[0-9a-f]{6}\.\w+$/, '').replace(/\.\w+$/, '').toLowerCase();

const block = [], kept = {free: 0, prop: 0};
for (const f of walk(path.join(ROOT, 'assets/era')).sort()) {
  const s = stem(f), c = credits.get(s);
  if (c && c.film) { block.push(rel(f)); continue; }
  if (/^still|-still|still-/.test(s)) { block.push(rel(f)); continue; }
  if (c && c.free) { kept.free++; continue; }
  if (PROP.test(s)) { kept.prop++; continue; }
  block.push(rel(f));
}

const swap = {};
for (const [from, to] of [['galaxy-front', 'galaxy-front-app'], ['aisles', 'aisles-app']])
  for (const w of ['', '-1000', '-1400']) {
    const a = `assets/hero/${from}${w}.webp`, b = `assets/app/${to}${w}.webp`;
    if (fs.existsSync(path.join(ROOT, b))) swap[a] = b;
  }
/* the late show curtain: the shelves beside it carry poster lookalike covers */
if (fs.existsSync(path.join(ROOT, 'assets/app/latedoor-app.webp'))) swap['assets/hero/latedoor.webp'] = 'assets/app/latedoor-app.webp';

/* per-film poster art made for the app, keyed by film id ("Title (Year)") */
const films = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/films.json'), 'utf8'));
const slug = id => id.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const posterFiles = new Map(walk(path.join(ROOT, 'assets/type-posters')).filter(f => /\.(webp|jpe?g|png)$/i.test(f)).map(f => [path.basename(f).replace(/\.\w+$/, ''), rel(f)]));
const posters = {};
for (const e of films) { const id = `${e.title} (${e.year})`, p = posterFiles.get(slug(id)); if (p) posters[id] = p; }

const out = `/* Generated by scripts/app-art.cjs. Do not edit by hand.
   Pictures the app build leaves out, and the app copies that replace them (docs/APP-BUILD.md). */
window.APP_ART=${JSON.stringify({swap, prefix: ['assets/menu-posters/', 'assets/menu-details/'], block, posters})};
`;
fs.writeFileSync(path.join(ROOT, 'app-art.js'), out);
console.log(`app-art.js: ${block.length} menu pictures blocked, ${kept.free} credited free pictures and ${kept.prop} textures or props kept, ${Object.keys(swap).length} shop photos swapped, ${Object.keys(posters).length} poster images found`);
