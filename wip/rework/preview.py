"""Preview a reworked menu.
Usage: python3 preview.py <fmt>
Reads rework/<fmt>.js (just the renderer function), installs it into the local site copy for that one menu,
renders the film in a real browser, saves rework/shots/<fmt>.jpg (the saved-image export) and
rework/shots/<fmt>_phone.png, and prints readability numbers."""
import asyncio, json, os, sys, subprocess, base64
from urllib.parse import quote
R = os.path.dirname(os.path.abspath(__file__))
REPO = '/tmp/claude-0/-home-claude/255d9f36-a28f-53a9-8508-211dbc596b89/scratchpad/prevwt'
fmt = sys.argv[1]
src = open(os.path.join(R, fmt + '.js')).read().rstrip() + '\n'
chunk_path = os.path.join(REPO, 'formats', fmt + '.js')
chunk = open(chunk_path).read()
i = chunk.index('FMT_RENDER[')
header = '/* Generated by scripts/build-formats.cjs from formats.js. Do not edit by hand. */\n'
ovr = os.path.join(R, fmt + '.labels.json')
tail = ''
if os.path.exists(ovr):
    tail = '\n;(()=>{const O=' + open(ovr).read() + ';for(const id in O){const sp=FMT_FILMS[id];if(!sp)continue;for(const g of sp.groups)for(const it of g.items){const o=O[id][it.k];if(o)Object.assign(it,o)}}})();\n'
open(chunk_path, 'w').write(header + src + chunk[i:] + tail)
# syntax check
r = subprocess.run(['node', '--check', chunk_path], capture_output=True, text=True)
if r.returncode: print('SYNTAX ERROR\n' + r.stderr[:1500]); sys.exit(1)
films = [x for x in json.load(open(os.path.join(R, 'list.json'))) if x['fmt'] == fmt][0]['films']
# make sure the local server is up
if subprocess.run(['curl', '-s', '-o', '/dev/null', 'http://localhost:8777/']).returncode:
    subprocess.Popen(['python3', '-m', 'http.server', '8777'], cwd=REPO, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)
    import time; time.sleep(1.5)
from playwright.async_api import async_playwright
METRICS = """()=>{const c=document.querySelector('#preview .mcard');if(!c||!c.classList.contains('fmt'))return {error:'menu did not render'};
 const sizes=[];const w=document.createTreeWalker(c,NodeFilter.SHOW_TEXT);let n;const cr=c.getBoundingClientRect();const spill=[];
 while((n=w.nextNode())){const t=n.textContent.trim();if(!t)continue;const el=n.parentElement;if(el.closest('[aria-hidden=true]'))continue;
  if(t.length>=28)sizes.push([parseFloat(getComputedStyle(el).fontSize),t.slice(0,40)]);
  const rg=document.createRange();rg.selectNodeContents(n);const rs=[...rg.getClientRects()];if(!rs.length)continue;
  const b=Math.max(...rs.map(x=>x.bottom)),r=Math.max(...rs.map(x=>x.right));
  if(b>cr.bottom+1||r>cr.right+1){spill.push('off page: '+t.slice(0,30));continue}
  let a=el;while(a&&a!==c){const cs=getComputedStyle(a);const box=a.getBoundingClientRect();
   const boxed=(a.style.height||a.style.maxHeight||cs.overflow!=='visible')&&(cs.backgroundColor!=='rgba(0, 0, 0, 0)'||cs.backgroundImage!=='none'||cs.borderBottomWidth!=='0px'||cs.overflow!=='visible');
   if(boxed&&(b>box.bottom+2||r>box.right+2)){spill.push('out of its card: '+t.slice(0,30));break}a=a.parentElement}}
 sizes.sort((a,b)=>a[0]-b[0]);
 return {smallestText:sizes.slice(0,4),SPILL:spill.slice(0,6)}}"""
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        for fid in films:
            pg = await (await b.new_context(viewport={'width': 1400, 'height': 1000})).new_page()
            errs = []
            pg.on('pageerror', lambda e: errs.append(str(e)))
            await pg.goto('http://localhost:8777/?film=' + quote(fid)); await pg.wait_for_timeout(8000)
            m = await pg.evaluate(METRICS)
            print(fid, json.dumps(m))
            try:
                data = await pg.evaluate("""async()=>{await loadExportTools(false);const c=await renderCanvas(document.querySelector('#preview .mcard'),false);return c.toDataURL('image/jpeg',.82)}""")
                open(os.path.join(R, 'shots', fmt + '.jpg'), 'wb').write(base64.b64decode(data.split(',')[1]))
                print('saved', os.path.join(R, 'shots', fmt + '.jpg'))
            except Exception as e: print('EXPORT FAILED', e)
            mp = await (await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True)).new_page()
            await mp.goto('http://localhost:8777/?film=' + quote(fid)); await mp.wait_for_timeout(6000)
            await mp.evaluate("document.querySelectorAll('.welcome').forEach(e=>e.remove());document.getElementById('fmtPhone').scrollIntoView()")
            await mp.wait_for_timeout(300)
            el = await mp.query_selector('#fmtPhone')
            if el: await el.screenshot(path=os.path.join(R, 'shots', fmt + '_phone.png'))
            print('page errors', errs[:3])
        await b.close()
asyncio.run(main())
