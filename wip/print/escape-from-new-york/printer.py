def _disc(d):
    """soft round dot, antialiased, at 2x pixels"""
    r = d * S / 2
    n = int(math.ceil(r * 2)) + 2
    yy, xx = np.mgrid[0:n * 4, 0:n * 4] / 4.0
    c = n / 2
    m = ((xx - c) ** 2 + (yy - c) ** 2) <= r * r
    a = m.reshape(n, 4, n, 4).mean(axis=(1, 3))
    return a.astype(np.float32), c


class Sheet:
    def __init__(self, w, h, seed):
        self.w, self.h = w, h
        self.a = np.zeros((h * S, w * S), np.float32)
        self.rnd = random.Random(seed)
        self.stamp, self.c = _disc(DOT)
        self.nrs = np.random.RandomState(seed)

    def ribbon(self, y):
        """how much ink this stretch of ribbon gives a line at page height y (css px)"""
        return 0.84 + 0.1 * math.sin(y / 61.0) + 0.05 * math.sin(y / 23.0 + 1.3)

    def dot(self, x, y, k):
        st = self.stamp
        X = int(round(x * S - self.c)); Y = int(round(y * S - self.c))
        n = st.shape[0]
        if X < 0 or Y < 0 or X + n > self.a.shape[1] or Y + n > self.a.shape[0]:
            return
        reg = self.a[Y:Y + n, X:X + n]
        self.a[Y:Y + n, X:X + n] = 1 - (1 - reg) * (1 - st * k)

    def text(self, x, y, s, sx=1, sy=1, bold=False, ink=1.0):
        """x, y: css px of the top-left of the cap row. Returns the x after the last cell."""
        rib = self.ribbon(y) * ink
        for ch in s:
            g = G.get(ch)
            if g is None and ch != ' ':
                g = G.get(ch.upper())
            if g:
                jy = self.rnd.choice((0, 0, 0, 0.35, -0.35, 0.6))
                chk = self.rnd.uniform(0.9, 1.04)
                for ri, row in enumerate(g):
                    top_light = 0.8 if ri == 0 else (0.9 if ri == 1 else 1.0)
                    for ci, b in enumerate(row):
                        if b != '#':
                            continue
                        for ky in range(sy):
                            for kx in range(sx):
                                px = x + (ci * sx + kx) * HP
                                py = y + jy + (ri * sy + ky) * VP
                                k = min(1, 0.9 * rib * chk * top_light * self.rnd.uniform(0.86, 1.05))
                                self.dot(px, py, k)
                                if bold:
                                    self.dot(px + HP / 2, py, k * 0.95)
            x += CELL * sx
        return x

    def width(self, s, sx=1):
        return len(s) * CELL * sx

    def save(self, path):
        h, w = self.a.shape
        out = np.zeros((h, w, 4), np.uint8)
        out[..., 0], out[..., 1], out[..., 2] = INK
        out[..., 3] = np.clip(self.a * 242, 0, 255).astype(np.uint8)
        Image.fromarray(out, 'RGBA').save(path, optimize=True)
